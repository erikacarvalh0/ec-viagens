import { expect, test } from "@playwright/test";
import { randomUUID } from "node:crypto";

test("creates, edits, archives and restores a trip", async ({ page }) => {
  test.setTimeout(90000);
  const email = `trip-${randomUUID()}@example.test`;
  const password = "trip-password-12345";
  const name = "Viagem E2E";
  const edited = "Viagem E2E atualizada";
  await page.goto("/register");
  await page.getByLabel("Nome").fill("Trip Browser Test");
  await page.getByLabel("E-mail").fill(email);
  await page.getByLabel("Senha").fill(password);
  await page.getByRole("button", { name: "Cadastrar", exact: true }).click();
  await expect(page).toHaveURL(/\/login\?registered=1/);
  await page.getByLabel("E-mail").fill(email);
  await page.getByLabel("Senha").fill(password);
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.getByRole("button", { name: "Nova viagem", exact: true }).click();
  await page.getByLabel("Nome da viagem *").fill(name);
  await page.getByRole("button", { name: "Criar viagem", exact: true }).click();
  await page.getByRole("button", { name: `Ver detalhes de ${name}` }).click();
  await page.getByRole("link", { name: "Visão geral da viagem" }).click();
  await expect(page.getByRole("heading", { name, exact: true })).toBeVisible();
  await expect(page).toHaveURL(/\/trips\/[^/]+\/overview$/);
  const overview = page.url();
  await page.getByRole("link", { name: "Editar dados da viagem" }).click();
  await page.getByLabel("Nome da viagem *").fill(edited);
  await page.getByRole("button", { name: "Salvar alterações" }).click();
  await expect(page.getByRole("status")).toContainText("Viagem atualizada.");
  await page.goto(overview);
  await expect(page.getByRole("heading", { name: edited, exact: true })).toBeVisible();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Arquivar viagem", exact: true }).click();
  await expect(page.getByText("Esta viagem está arquivada.")).toBeVisible();
  await page.goto("/dashboard");
  await expect(page.getByRole("heading", { name: edited, exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Histórico de viagens" }).click();
  await expect(page.getByRole("heading", { name: edited, exact: true })).toBeVisible();
  await page.goto(overview);
  await page.getByRole("button", { name: "Restaurar viagem" }).click();
  await expect(page.getByRole("button", { name: "Arquivar viagem", exact: true })).toBeVisible();
  await page.goto("/dashboard");
  await expect(page.getByRole("heading", { name: edited, exact: true })).toBeVisible();
});
